package Personas2;

public class Pessoas2 {
    private String name;
    private int idade;

    public Pessoas2(String name, int idade) {
        this.name = name;
        this.idade = idade;
    }
    public Pessoas2(){}

    public String getName() {
        return name;
    }

    public int getIdade() {
        return idade;
    }
}
